#!/usr/bin/env python3
"""Differential fuzzing harness: C Graphviz 16.1.0 versus the port.

  run      generate cases with scripts/fuzz-gen.py and compare C `dot -Tsvg` with
           the port's release and debug `graphviz-pure -Tsvg` (stdout minus the generator
           comment, exit status, stderr), recording every outcome
  min      delta-debug one case to a small input that keeps the same kind of difference
  check    print the outcome for each given file
  summary  print statistics of a run directory

Usage:
  python3 -I scripts/fuzz-run.py run --seed 1 --count 1000 --out /tmp/fuzz/r1 [--engine E]
  python3 -I scripts/fuzz-run.py min /tmp/fuzz/r1/diff/s17.gv [-o min.gv]
  python3 -I scripts/fuzz-run.py summary /tmp/fuzz/r1

C runs with GVBINDIR (default ~/src/gv-ref/lutplugins: built-in text metrics, as the
goldens). Outcomes (one JSON line per case in OUT/results.jsonl):
  same         stdout and exit status agree for release and debug (stderr may differ:
               field `stderr_diff`)
  c_timeout    C exceeded the timeout          c_crash    C died from a signal
  c_unstable   C's output differs between two runs
  svg_diff     stdout differs                  exit_diff  exit status differs
  port_crash   the port panicked or died       port_timeout  the port exceeded the timeout
  debug_diff   the debug build (overflow checks) panicked or disagreed with release
Cases with an actionable outcome are copied to OUT/diff/.
"""
import argparse
import collections
import concurrent.futures as cf
import importlib.util
import json
import os
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
GVBINDIR = os.environ.get("GVBINDIR", str(pathlib.Path.home() / "src/gv-ref/lutplugins"))
C_BIN = os.environ.get("C_DOT", "dot")
REL = os.environ.get("PORT_BIN", str(ROOT / "target/release/graphviz-pure"))
DBG = os.environ.get("PORT_DEBUG_BIN", str(ROOT / "target/debug/graphviz-pure"))
TIMEOUT = float(os.environ.get("FUZZ_TIMEOUT", "30"))
ACTIONABLE = {"svg_diff", "exit_diff", "port_crash", "port_timeout", "debug_diff"}


def load_gen():
    spec = importlib.util.spec_from_file_location("fuzzgen", ROOT / "scripts/fuzz-gen.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def normalize(out):
    return b"".join(l for l in out.splitlines(keepends=True) if not l.startswith(b"<!-- Generated by "))


def norm_err(err, path):
    s = err.decode("utf-8", "replace").replace(str(path), "FILE")
    return re.sub(r"^(dot|graphviz-pure): ", "PROG: ", s, flags=re.M)


def run(cmd, path, timeout=TIMEOUT, env=None):
    """Returns (status, stdout, stderr); status is 'timeout' or an int (negative: signal)."""
    try:
        p = subprocess.run(cmd + ["-Tsvg", str(path)], capture_output=True, timeout=timeout,
                           env=env, stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return "timeout", b"", b""
    return p.returncode, normalize(p.stdout), p.stderr


C_ENV = dict(os.environ, GVBINDIR=GVBINDIR)


def run_c(path):
    return run([C_BIN], path, env=C_ENV)


def is_panic(res):
    st, _, err = res
    return st == 101 or (isinstance(st, int) and st < 0) or b"panicked at" in err


def classify(path, c=None, need_stable=True, debug=True):
    """Compares C and the port on one input; returns (outcome, details)."""
    c = c or run_c(path)
    d = {}
    if c[0] == "timeout":
        return "c_timeout", d
    if c[0] < 0:
        return "c_crash", {"signal": -c[0]}
    rel = run([REL], path, timeout=TIMEOUT * 2)
    outcome = None
    if rel[0] == "timeout":
        outcome = "port_timeout"
    elif is_panic(rel):
        outcome = "port_crash"
        d["panic"] = rel[2].decode("utf-8", "replace")[-400:]
    elif rel[0] != c[0]:
        outcome = "exit_diff"
        d["c_status"], d["port_status"] = c[0], rel[0]
    elif rel[1] != c[1]:
        outcome = "svg_diff"
    if outcome is None and debug:
        dbg = run([DBG], path, timeout=TIMEOUT * 4)
        if dbg[0] != "timeout" and (is_panic(dbg) or dbg[1] != rel[1] or dbg[0] != rel[0]):
            outcome = "debug_diff"
            d["panic"] = dbg[2].decode("utf-8", "replace")[-400:]
    if outcome in ("svg_diff", "exit_diff"):
        if norm_err(c[2], path) != norm_err(rel[2], path):
            d["stderr_diff"] = True
    elif outcome is None:
        if norm_err(c[2], path) != norm_err(rel[2], path):
            d["stderr_diff"] = True
        return "same", d
    if need_stable and outcome in ("svg_diff", "exit_diff"):
        c2 = run_c(path)
        if c2[:2] != c[:2]:
            return "c_unstable", d
    return outcome, d


def first_diff_line(a, b):
    al, bl = a.splitlines(), b.splitlines()
    for i, (x, y) in enumerate(zip(al, bl)):
        if x != y:
            return i, x.decode("utf-8", "replace")[:200], y.decode("utf-8", "replace")[:200]
    return min(len(al), len(bl)), "<eof>" if len(al) < len(bl) else "", "<eof>" if len(bl) < len(al) else ""


def cmd_run(a):
    gen = load_gen()
    out = a.out
    (out / "cases").mkdir(parents=True, exist_ok=True)
    (out / "diff").mkdir(exist_ok=True)
    seeds = range(a.seed, a.seed + a.count)

    def one(s):
        g = gen.Gen(s, a.engine, a.malformed)
        text = g.case()
        p = out / "cases" / f"s{s}.gv"
        p.write_text(text, encoding="utf-8")
        oc, d = classify(p)
        rec = {"seed": s, "engine": g.engine, "malformed": g.malformed, "outcome": oc, **d}
        if oc in ACTIONABLE:
            (out / "diff" / p.name).write_text(text, encoding="utf-8")
        else:
            p.unlink()
        return rec

    n = 0
    with open(out / "results.jsonl", "a") as f, cf.ThreadPoolExecutor(a.jobs) as ex:
        for rec in ex.map(one, seeds):
            f.write(json.dumps(rec) + "\n")
            f.flush()
            n += 1
            if rec["outcome"] != "same":
                print(f"[{n}/{a.count}] s{rec['seed']} {rec['engine']} {rec['outcome']}", flush=True)
    summarize(out)


def summarize(out):
    recs = [json.loads(l) for l in open(out / "results.jsonl")]
    by = collections.defaultdict(collections.Counter)
    for r in recs:
        by[r["engine"]][r["outcome"]] += 1
        by["ALL"][r["outcome"]] += 1
        if r.get("stderr_diff"):
            by[r["engine"]]["(stderr_diff)"] += 1
            by["ALL"]["(stderr_diff)"] += 1
    keys = ["same", "svg_diff", "exit_diff", "port_crash", "port_timeout", "debug_diff",
            "c_unstable", "c_timeout", "c_crash", "(stderr_diff)"]
    print("engine     cases  same%  " + " ".join(k[:10].rjust(10) for k in keys[1:]))
    for e in sorted(by, key=lambda x: (x == "ALL", x)):
        c = by[e]
        tot = sum(v for k, v in c.items() if not k.startswith("("))
        comparable = tot - c["c_unstable"] - c["c_timeout"] - c["c_crash"]
        pct = 100.0 * c["same"] / comparable if comparable else 0
        print(f"{e:9} {tot:6} {pct:6.2f}  " + " ".join(str(c[k]).rjust(10) for k in keys[1:]))


# ---- minimiser ---------------------------------------------------------------

def split_attrs(body):
    """Splits the inside of `[...]` at top-level commas, respecting quotes and <...>."""
    parts, cur, depth, inq, esc = [], "", 0, False, False
    for ch in body:
        if inq:
            cur += ch
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                inq = False
            continue
        if ch == '"':
            inq = True
        elif ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif ch in ",;" and depth == 0:
            parts.append(cur.strip())
            cur = ""
            continue
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def attr_span(line):
    """Returns (start, end) of the last top-level `[...]` of a line, or None."""
    inq, esc, depth, start = False, False, 0, None
    span = None
    for i, ch in enumerate(line):
        if inq:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                inq = False
            continue
        if ch == '"':
            inq = True
        elif ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif ch == "[" and depth == 0 and start is None:
            start = i
        elif ch == "]" and depth == 0 and start is not None:
            span = (start, i)
            start = None
    return span


def blocks(lines):
    """Pairs (open_index, close_index) of `... {` / `}` lines."""
    st, out = [], []
    for i, l in enumerate(lines):
        s = l.rstrip()
        if s.endswith("{") and not s.endswith("{{"):
            st.append(i)
        elif s == "}" and st:
            out.append((st.pop(), i))
    return out


def minimize(path, outcome, log=print):
    lines = pathlib.Path(path).read_text(encoding="utf-8").splitlines()
    tmpdir = pathlib.Path(tempfile.mkdtemp(prefix="fuzzmin"))
    tries = [0]

    def test(cand):
        tries[0] += 1
        p = tmpdir / "t.gv"
        p.write_text("\n".join(cand) + "\n", encoding="utf-8")
        oc, _ = classify(p, need_stable=False, debug=(outcome == "debug_diff"))
        return oc == outcome

    if not test(lines):
        log("difference does not reproduce")
        return None

    changed = True
    while changed:
        changed = False
        # 1. whole blocks (subgraphs), largest first
        for o, c in sorted(blocks(lines), key=lambda b: b[0] - b[1]):
            if c >= len(lines) or o == 0:
                continue
            cand = lines[:o] + lines[c + 1:]
            if test(cand):
                lines, changed = cand, True
                break
        if changed:
            continue
        # 2. chunks of plain lines (ddmin)
        removable = [i for i, l in enumerate(lines)
                     if 0 < i < len(lines) - 1 and not l.rstrip().endswith("{") and l.strip() != "}"]
        k = max(1, len(removable) // 2)
        while k >= 1 and removable:
            j = 0
            progress = False
            while j < len(removable):
                drop = set(removable[j:j + k])
                cand = [l for i, l in enumerate(lines) if i not in drop]
                if test(cand):
                    lines = cand
                    removable = [i for i, l in enumerate(lines)
                                 if 0 < i < len(lines) - 1 and not l.rstrip().endswith("{") and l.strip() != "}"]
                    changed = progress = True
                else:
                    j += k
            if not progress:
                k //= 2
        # 3. flatten blocks (drop the braces, keep the contents)
        for o, c in blocks(lines):
            if o == 0 or c >= len(lines) - 1 and c == len(lines) - 1 and o == 0:
                continue
            cand = [l for i, l in enumerate(lines) if i not in (o, c)]
            if test(cand):
                lines, changed = cand, True
                break
        if changed:
            continue
        # 4. attributes within lines
        for i in range(len(lines)):
            while True:
                sp = attr_span(lines[i])
                if not sp:
                    break
                parts = split_attrs(lines[i][sp[0] + 1:sp[1]])
                done = True
                for j in range(len(parts)):
                    rest = parts[:j] + parts[j + 1:]
                    nl = lines[i][:sp[0] + 1] + ", ".join(rest) + lines[i][sp[1]:]
                    if test(lines[:i] + [nl] + lines[i + 1:]):
                        lines[i] = nl
                        changed, done = True, False
                        break
                if done:
                    break
    log(f"minimised to {len(lines)} lines in {tries[0]} tries")
    return "\n".join(lines) + "\n"


def cmd_check(a):
    def one(f):
        return f, classify(pathlib.Path(f), debug=not a.no_debug)
    with cf.ThreadPoolExecutor(a.jobs) as ex:
        for f, (oc, d) in ex.map(one, a.files):
            if not a.quiet or oc != "same":
                print(f"{oc:12} {f} {d.get('panic', '')[-200:]!s}".rstrip())


def cmd_min(a):
    p = pathlib.Path(a.case)
    oc, d = classify(p)
    print(f"outcome: {oc} {d if d else ''}")
    if oc not in ACTIONABLE:
        return 1
    res = minimize(p, oc)
    if res is None:
        return 1
    if a.o:
        pathlib.Path(a.o).write_text(res, encoding="utf-8")
    else:
        sys.stdout.write(res)
    return 0


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--seed", type=int, default=1)
    r.add_argument("--count", type=int, default=100)
    r.add_argument("--out", type=pathlib.Path, required=True)
    r.add_argument("--engine")
    r.add_argument("--malformed", type=float, default=0.08)
    r.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 4) - 2))
    m = sub.add_parser("min")
    m.add_argument("case")
    m.add_argument("-o")
    c = sub.add_parser("check")
    c.add_argument("files", nargs="+")
    c.add_argument("--no-debug", action="store_true")
    c.add_argument("-q", "--quiet", action="store_true", help="only print differences")
    c.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 4) - 2))
    s = sub.add_parser("summary")
    s.add_argument("out", type=pathlib.Path)
    a = ap.parse_args()
    if a.cmd == "run":
        cmd_run(a)
    elif a.cmd == "check":
        cmd_check(a)
    elif a.cmd == "min":
        sys.exit(cmd_min(a))
    else:
        summarize(a.out)


if __name__ == "__main__":
    main()
