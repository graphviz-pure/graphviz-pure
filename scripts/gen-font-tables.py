#!/usr/bin/env python3
"""Generate crates/graphviz-pure-core/src/font_tables.rs from the Graphviz C sources.

Sources (Graphviz 16.1.0):
  lib/common/textspan_lut.c   -> FONT_METRICS (per-family ASCII advance widths)
  lib/common/ps_font_equiv.h  -> POSTSCRIPT_ALIASES (postscript_alias[] in textspan.c)
  lib/common/entities.h       -> HTML_ENTITIES, ENTITY_NAME_LENGTH_MAX (used by htmlEntityUTF8)

Usage: scripts/gen-font-tables.py [GRAPHVIZ_SRC_DIR] > crates/graphviz-pure-core/src/font_tables.rs
       (default GRAPHVIZ_SRC_DIR: ~/src/gv-ref/graphviz-16.1.0)

The script is deterministic: rerunning it on the same C sources yields a byte-identical file,
so `git diff` after regeneration proves every entry still matches C.
"""

import os
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/src/gv-ref/graphviz-16.1.0")
common = os.path.join(src, "lib", "common")


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_lut():
    text = strip_comments(open(os.path.join(common, "textspan_lut.c")).read())
    start = text.index("all_font_metrics[] = {")
    end = text.index("};", start)
    body = text[start + len("all_font_metrics[] = {"):end]
    families = []
    # Each family: { (const char *[]){names, NULL}, units, {..}, {..}, {..}, {..}, }
    for m in re.finditer(
        r"\(const char \*\[\]\)\{(?P<names>[^}]*)\}\s*,\s*(?P<units>[0-9.]+)\s*,"
        r"(?P<arrays>(?:\s*\{[^}]*\}\s*,){4})",
        body,
    ):
        names = re.findall(r'"([^"]*)"', m.group("names"))
        assert m.group("names").strip().endswith("NULL"), m.group("names")
        arrays = re.findall(r"\{([^}]*)\}", m.group("arrays"))
        assert len(arrays) == 4
        widths = []
        for a in arrays:
            vals = [int(v) for v in re.findall(r"-?\d+", a)]
            assert len(vals) == 128, (names, len(vals))
            widths.append(vals)
        families.append((names, m.group("units"), widths))
    assert len(families) == body.count("(const char *[])"), "unparsed family"
    return families


def parse_aliases():
    text = strip_comments(open(os.path.join(common, "ps_font_equiv.h")).read())
    macros = dict(re.findall(r'#define\s+(\w+)\s+"([^"]*)"', text))
    # Non-Windows build: TIMES is "Times" (the #else branch).
    macros["TIMES"] = "Times"
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        inner = line[1 : line.rindex("}")]
        fields = [f.strip() for f in re.findall(r'"[^"]*"|[^,]+', inner)]
        fields = [f for f in fields if f]
        assert len(fields) == 9, line

        def s(f):
            if f.startswith('"'):
                return f[1:-1]
            if f == "0":
                return None
            return macros[f]

        rows.append(
            (s(fields[0]), s(fields[1]), s(fields[2]), s(fields[3]), s(fields[4]),
             int(fields[5]), s(fields[6]), s(fields[7]), s(fields[8]))
        )
    return rows


def parse_entities():
    text = open(os.path.join(common, "entities.h")).read()
    rows = [(n, int(v)) for n, v in re.findall(r'\{"(\w+)",\s*(\d+)\}', text)]
    maxlen = int(re.search(r"#define ENTITY_NAME_LENGTH_MAX (\d+)", text).group(1))
    names = [n for n, _ in rows]
    # bsearch() with strcmp-like ordering: plain byte order.
    assert names == sorted(names), "entity table not sorted"
    return rows, maxlen


def rs_opt(v):
    return "None" if v is None else f'Some("{v}")'


def main():
    out = []
    w = out.append
    w("// @generated by scripts/gen-font-tables.py from Graphviz 16.1.0")
    w("// (lib/common/textspan_lut.c and lib/common/ps_font_equiv.h). Do not edit by hand.")
    w("")
    w("use super::{FontFamilyMetrics, PostscriptFontAlias};")
    w("")
    fams = parse_lut()
    w("/// `all_font_metrics[]` from `lib/common/textspan_lut.c`, in C order.")
    w(f"pub(crate) static FONT_METRICS: [FontFamilyMetrics; {len(fams)}] = [")
    for names, units, widths in fams:
        w("    FontFamilyMetrics {")
        w("        font_names: &[" + ", ".join(f'"{n}"' for n in names) + "],")
        w(f"        units_per_em: {float(units)!r},")
        for label, vals in zip(
            ["widths_regular", "widths_bold", "widths_italic", "widths_bold_italic"], widths
        ):
            w(f"        {label}: [")
            for i in range(0, 128, 16):
                w("            " + ", ".join(str(v) for v in vals[i : i + 16]) + ",")
            w("        ],")
        w("    },")
    w("];")
    w("")
    rows = parse_aliases()
    names = [r[0] for r in rows]
    # textspan.c bsearch()es this table with strcasecmp, so it must be sorted case-insensitively.
    assert names == sorted(names, key=lambda n: n.lower()), "alias table not sorted"
    w("/// `postscript_alias[]` from `lib/common/textspan.c` (`#include \"ps_font_equiv.h\"`),")
    w("/// non-Windows build (`TIMES` = `\"Times\"`). Sorted case-insensitively by name.")
    w(f"pub(crate) static POSTSCRIPT_ALIASES: [PostscriptFontAlias; {len(rows)}] = [")
    for r in rows:
        w("    PostscriptFontAlias {")
        w(f'        name: "{r[0]}",')
        w(f'        family: "{r[1]}",')
        w(f"        weight: {rs_opt(r[2])},")
        w(f"        stretch: {rs_opt(r[3])},")
        w(f"        style: {rs_opt(r[4])},")
        w(f"        xfig_code: {r[5]},")
        w(f'        svg_font_family: "{r[6]}",')
        w(f"        svg_font_weight: {rs_opt(r[7])},")
        w(f"        svg_font_style: {rs_opt(r[8])},")
        w("    },")
    w("];")
    w("")
    w("/// Rust-only exact-name storage dispatch; no C counterpart.")
    w("/// Borrow canonical names without searching or caching an owned-name miss.")
    w("pub(crate) fn static_postscript_fontname(name: &str) -> Option<&'static str> {")
    w("    Some(match name {")
    for i, r in enumerate(rows):
        w(f'        "{r[0]}" => POSTSCRIPT_ALIASES[{i}].name,')
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    ents, maxlen = parse_entities()
    w("/// `ENTITY_NAME_LENGTH_MAX` from `lib/common/entities.h`.")
    w(f"pub(crate) const ENTITY_NAME_LENGTH_MAX: usize = {maxlen};")
    w("")
    w("/// `entities[]` from `lib/common/entities.h` (byte-sorted by name).")
    w(f"pub(crate) static HTML_ENTITIES: [(&str, u32); {len(ents)}] = [")
    for n, v in ents:
        w(f'    ("{n}", {v}),')
    w("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
