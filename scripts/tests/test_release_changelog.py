"""Tests for release-changelog.py's section() (run with `python3 -m unittest`): only whole-line
HTML comments outside fenced code are stripped, so a literal `<!--` quoted in prose, a code span
or a fenced block cannot swallow the `## Changelog entry` heading (#479)."""
import importlib.util
import pathlib
import unittest

_spec = importlib.util.spec_from_file_location(
    "release_changelog", pathlib.Path(__file__).resolve().parents[1] / "release-changelog.py")
release_changelog = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(release_changelog)


class SectionTest(unittest.TestCase):
    def test_backticked_comment_marker_before_the_entry(self):
        # #468's shape: the generator comment quoted in a code span before the entry, and the
        # bot footer after the checklist. The old DOTALL `<!--.*?-->` strip deleted everything
        # from the span's `<!--` to the footer's first `-->`, heading included.
        body = (
            "Every SVG the port writes begins with `<!-- Generated by graphviz version 16.1.0` and\n"
            "never changes between releases.\n"
            "\n"
            "## Changelog entry\n"
            "\n"
            "- Fixed the widget. (#470)\n"
            "\n"
            "## Checklist\n"
            "\n"
            "<!-- codesmith:footer -->\n"
            "---\n"
            "<!-- /codesmith:footer -->\n")
        self.assertEqual(release_changelog.section(body), "\n- Fixed the widget. (#470)\n")

    def test_fenced_comment_marker_before_the_entry(self):
        # A fenced sample whose `<!--` has no `-->` inside the fence: the old strip ran on to the
        # footer's `-->` past the entry, so the entry was reported missing.
        body = (
            "The old output, verbatim:\n"
            "\n"
            "```\n"
            "<!-- Generated by graphviz-pure version 0.1.0 (Graphviz 16.1.0 port)\n"
            "```\n"
            "\n"
            "## Changelog entry\n"
            "\n"
            "Not user-visible.\n"
            "\n"
            "## Checklist\n"
            "\n"
            "<!-- codesmith:footer -->\n"
            "---\n"
            "<!-- /codesmith:footer -->\n")
        self.assertEqual(release_changelog.section(body), "\nNot user-visible.\n")

    def test_fenced_comment_marker_inside_the_entry_survives(self):
        # A fenced code sample in the entry keeps its `<!-- … -->` lines verbatim; the old strip
        # deleted them out of the fence.
        body = (
            "## Changelog entry\n"
            "\n"
            "### Changed\n"
            "\n"
            "- The generator comment is now version-free (#470). Before:\n"
            "\n"
            "```\n"
            "<!-- Generated by graphviz version 16.1.0 (graphviz-pure)\n"
            " -->\n"
            "```\n"
            "\n"
            "## Checklist\n")
        self.assertEqual(
            release_changelog.section(body),
            "\n### Changed\n\n- The generator comment is now version-free (#470). Before:\n\n"
            "```\n<!-- Generated by graphviz version 16.1.0 (graphviz-pure)\n -->\n```\n")

    def test_multiline_comment_and_footer_are_still_stripped(self):
        # The template's whole-line comments (spanning lines) and the bot footer markers still go;
        # a stripped entry that says "Not user-visible." is detected, as collect() does.
        body = (
            "## Changelog entry\n"
            "\n"
            "<!-- The release copies this section into CHANGELOG.md; don't edit CHANGELOG.md yourself.\n"
            "     One Keep a Changelog bullet per change. Nothing to say: write \"Not user-visible.\" -->\n"
            "\n"
            "Not user-visible.\n"
            "\n"
            "## Checklist\n"
            "\n"
            "<!-- codesmith:footer -->\n"
            "---\n"
            "<!-- /codesmith:footer -->\n")
        text = release_changelog.section(body)
        self.assertEqual(text, "\n\nNot user-visible.\n")
        bullets, prose = release_changelog.parse(text, None)
        self.assertEqual(bullets, [])
        self.assertTrue(release_changelog.NOT_VISIBLE.match(prose[0]))


class RenderTest(unittest.TestCase):
    def test_default_intro_counts_sections_in_changelog_order(self):
        data = {"entries": [
            {"section": "Fixed", "text": "Two. (#2)"},
            {"section": "Added", "text": "One. (#1)"},
            {"section": "Fixed", "text": "Three. (#3)"},
        ]}
        text = release_changelog.render(data, "0.2.4", None)
        self.assertIn("3 changes: 1 added, 2 fixed.", text)
        self.assertLess(text.index("### Added"), text.index("### Fixed"))

    def test_explicit_intro_replaces_the_counted_line(self):
        text = release_changelog.render({"entries": []}, "0.2.4", "Hello.")
        self.assertIn("Hello.", text)
        self.assertNotIn("No user-visible changes.", text)

    def test_no_entries_says_so(self):
        text = release_changelog.render({"entries": []}, "1.0.0", "")
        self.assertIn("No user-visible changes.", text)
        self.assertRegex(text.splitlines()[0], r"^## \[1\.0\.0\] - \d{4}-\d{2}-\d{2}$")


class VersionTest(unittest.TestCase):
    def test_explicit_major_can_exceed_computed_minor(self):
        minimum = release_changelog.next_version({"breaking": [1]}, "0.2.3")
        self.assertEqual(minimum, "0.3.0")
        self.assertTrue(release_changelog.version_at_least("1.0.0", minimum))
        self.assertFalse(release_changelog.version_at_least("0.2.4", minimum))

    def test_rc_route_and_semver_precedence(self):
        self.assertTrue(release_changelog.version_at_least("1.0.0-rc.1", "0.3.0"))
        minimum = release_changelog.next_version({"breaking": []}, "1.0.0-rc.1")
        self.assertEqual(minimum, "1.0.0")
        self.assertTrue(release_changelog.version_at_least("1.0.0", minimum))
        self.assertFalse(release_changelog.version_at_least("1.0.0-rc.1", minimum))
        self.assertTrue(release_changelog.version_at_least("1.0.0-rc.10", "1.0.0-rc.2"))

    def test_major_release_never_understates_the_minimum(self):
        minimum = release_changelog.next_version({"breaking": [1]}, "1.2.3")
        self.assertEqual(minimum, "2.0.0")
        self.assertTrue(release_changelog.version_at_least("3.0.0", minimum))
        self.assertFalse(release_changelog.version_at_least("1.3.0", minimum))


if __name__ == "__main__":
    unittest.main()
