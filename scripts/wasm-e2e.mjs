#!/usr/bin/env node
// WASM end-to-end check: renders every corpus input with the wasm build and compares the
// normalized SVG hash with C Graphviz's computed with the same math functions
// (tests/golden/e2e.libm-matched.json), like `gv-diff e2e` does for the native build. No npm packages are needed.
//
// Build the package first (see docs/porting/libm.md):
//   cargo build --release --target wasm32-unknown-unknown -p graphviz-pure-wasm
//   wasm-bindgen --target nodejs --out-dir /tmp/gvwasm/pkg \
//     target/wasm32-unknown-unknown/release/graphviz_pure_wasm.wasm
//   node scripts/export-graphviz-error.mjs /tmp/gvwasm/pkg/graphviz_pure_wasm.js
// then run from the repository root:
//   node scripts/wasm-e2e.mjs [--pkg /tmp/gvwasm/pkg] [--baseline FILE] [--filter SUBSTR]
//                             [--list] [--hashes FILE] [--golden FILE]
//
// Exits non-zero when a file in the baseline does not match under wasm. Every build uses the
// same math functions, so the default baseline is the native one,
// tests/golden/e2e-baseline.libm-matched.portable.json.
// `--hashes FILE` writes every output's hash in the format of `gv-diff e2e --hashes`, so the
// two can be compared with `cmp`.

import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { checkApi } from './wasm-runtimes/api-check.mjs';

const args = process.argv.slice(2);
let pkg = '/tmp/gvwasm/pkg';
let filter = null;
let list = false;
let baselinePath = 'tests/golden/e2e-baseline.libm-matched.portable.json';
let goldenPath = 'tests/golden/e2e.libm-matched.json';
let hashesPath = null;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--pkg') pkg = args[++i];
  else if (args[i] === '--filter') filter = args[++i];
  else if (args[i] === '--list') list = true;
  else if (args[i] === '--baseline') baselinePath = args[++i];
  else if (args[i] === '--hashes') hashesPath = args[++i];
  else if (args[i] === '--golden') goldenPath = args[++i];
  else {
    console.error(`unknown argument ${args[i]}`);
    process.exit(2);
  }
}
const require = createRequire(import.meta.url);
const gv = require(path.resolve(pkg, 'graphviz_pure_wasm.js'));

const root = process.cwd();
const packageVersion = JSON.parse(fs.readFileSync(path.join(root, 'web/package.json'), 'utf8')).version;
assert.equal(gv.version(), `graphviz version 16.1.0 (graphviz-pure ${packageVersion})`);
checkApi(gv);
const formats = gv.supportedFormats();
assert.ok(Array.isArray(formats) && formats.length > 0);
for (const format of formats) {
  assert.ok(gv.render('digraph { a -> b }', 'dot', format).length > 0, format);
}
console.log(`wasm API: version ${packageVersion}; ${formats.length} supported formats render`);

const golden = JSON.parse(fs.readFileSync(path.resolve(root, goldenPath), 'utf8')).files;
const baseline = new Set(
  JSON.parse(fs.readFileSync(path.resolve(root, baselinePath), 'utf8')).identical,
);
// Same table as crates/graphviz-pure-diff/src/e2e.rs.
const corpora = {
  main: ['tests/wild', 'tests/fixtures'],
  neato: ['tests/neato'],
  sfdp: ['tests/sfdp'],
  circo: ['tests/circo'],
  twopi: ['tests/twopi'],
  fdp: ['tests/fdp'],
  osage: ['tests/osage'],
  patchwork: ['tests/patchwork'],
  render: ['tests/render'],
};

// Drops the generator comment, which names the program and version.
function normalize(bytes) {
  const out = [];
  let start = 0;
  const skip = Buffer.from('<!-- Generated by ');
  while (start < bytes.length) {
    let end = bytes.indexOf(0x0a, start);
    end = end < 0 ? bytes.length : end + 1;
    const line = bytes.subarray(start, end);
    if (!line.subarray(0, skip.length).equals(skip)) out.push(line);
    start = end;
  }
  return Buffer.concat(out);
}
// FNV-1a, 64-bit.
function fnv(bytes) {
  let h = 0xcbf29ce484222325n;
  for (const x of bytes) {
    h ^= BigInt(x);
    h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return h.toString(16).padStart(16, '0');
}
// Renders every graph in the file, as `gv-diff e2e` does. `renderAllBytes` keeps non-UTF-8
// input bytes (charset=latin1 files) the way the native harness does.
function renderAll(bytes) {
  if (gv.renderAllBytes) return Buffer.from(gv.renderAllBytes(bytes, 'dot', 'svg'));
  const src = bytes.toString('utf8');
  if (gv.renderAll) return Buffer.from(gv.renderAll(src, 'dot', 'svg').join(''), 'utf8');
  return Buffer.from(gv.render(src, 'dot', 'svg'), 'utf8');
}

const t0 = Date.now();
const per = {};
const hashes = {};
const bad = [];
let regressions = 0;
for (const [c, dirs] of Object.entries(corpora)) {
  const r = (per[c] = { total: 0, identical: 0, differ: 0, error: 0, inBaseline: 0 });
  for (const d of dirs) {
    const dir = path.join(root, d);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.gv')).sort()) {
      const key = `${c}/${f.slice(0, -3)}`;
      if (!golden[key] || (filter && !key.includes(filter))) continue;
      r.total++;
      if (baseline.has(key)) r.inBaseline++;
      const src = fs.readFileSync(path.join(dir, f));
      let out;
      try {
        out = renderAll(src);
      } catch (e) {
        r.error++;
        hashes[key] = null;
        bad.push(`${key} ERROR ${String(e).slice(0, 80)}`);
        if (baseline.has(key)) regressions++;
        continue;
      }
      const h = (hashes[key] = fnv(normalize(out)));
      if (h === golden[key]) r.identical++;
      else {
        r.differ++;
        bad.push(key);
        if (baseline.has(key)) regressions++;
      }
    }
  }
}
console.log('corpus     total  wasm-identical          baseline  differ  error');
const sum = { total: 0, identical: 0, inBaseline: 0, differ: 0, error: 0 };
for (const [c, r] of Object.entries(per)) {
  if (!r.total) continue;
  for (const k of Object.keys(sum)) sum[k] += r[k];
  console.log(
    `${c.padEnd(10)} ${String(r.total).padStart(5)}  ${String(r.identical).padStart(14)}  ${String(r.inBaseline).padStart(16)}  ${String(r.differ).padStart(6)}  ${String(r.error).padStart(5)}`,
  );
}
console.log(
  `${'all'.padEnd(10)} ${String(sum.total).padStart(5)}  ${String(sum.identical).padStart(14)}  ${String(sum.inBaseline).padStart(16)}  ${String(sum.differ).padStart(6)}  ${String(sum.error).padStart(5)}`,
);
console.log(`${((Date.now() - t0) / 1000).toFixed(1)}s; ${regressions} file(s) of ${baselinePath} differ under wasm`);
if (list) console.log(bad.join('\n'));
if (hashesPath) {
  const sorted = Object.fromEntries(Object.keys(hashes).sort().map((k) => [k, hashes[k]]));
  fs.writeFileSync(hashesPath, JSON.stringify(sorted, null, 2) + '\n');
  console.log(`hashes written: ${hashesPath}`);
}
process.exit(regressions ? 1 : 0);
